/**
 * 路線IDから路線情報を取得
 * @param {string} railwayId - 路線ID
 * @returns {Object|null} - 路線情報
 */
function getRailwayById(railwayId) {
  return ODPT_RAILWAYS.find(r => r.id === railwayId) || null;
}

/**
 * 駅名で駅を検索
 * @param {string} name - 駅名（部分一致）
 * @returns {Array} - マッチした駅一覧
 */
function searchStationsByName(name) {
  const results = [];
  const searchName = name.toLowerCase();

  ODPT_RAILWAYS.forEach(railway => {
    railway.stations.forEach(station => {
      if (station.name.toLowerCase().includes(searchName)) {
        results.push({
          ...station,
          railway: railway.id,
          railwayName: railway.name,
          operator: railway.operator,
          color: railway.color
        });
      }
    });
  });

  return results;
}

/**
 * 事業者別の路線一覧を取得
 * @param {string} operator - 事業者ID（省略時は全て）
 * @returns {Array} - 路線一覧
 */
function getRailwaysByOperator(operator) {
  if (!operator) {
    return ODPT_RAILWAYS;
  }
  return ODPT_RAILWAYS.filter(r => r.operator === operator);
}
